import AppKit
import SwiftUI

/// Recent copied text (設定 › 功能 › 剪貼簿歷史, off by default). Kept in memory only: nothing is written to disk and it
/// is gone when the app quits. Items that password managers mark as concealed or transient are never kept.
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    struct Item: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let copied: Date
        var pinned = false
    }

    static let maxItems = 50
    static let maxLength = 5_000
    /// How long an unpinned item is kept (設定: 1 hour / 1 day / 7 days).
    static var keepSeconds: TimeInterval { Double(max(1, AppSettings.shared.clipboardKeepHours)) * 3600 }

    @Published private(set) var items: [Item] = []
    /// macOS refuses this app the pasteboard (System Settings › Privacy & Security › Paste from Other Apps).
    @Published private(set) var denied = false

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var ownChange = -1

    /// Follows the setting: watches the pasteboard, or stops and forgets everything.
    func apply(enabled: Bool) {
        timer?.invalidate(); timer = nil
        guard enabled else { items = []; return }
        lastChange = NSPasteboard.general.changeCount   // only what is copied from now on
        timer = Timer.commonModeTimer(interval: 0.75, repeats: true) { [weak self] _ in self?.poll() }
    }

    /// Types that mean "do not record this" (nspasteboard.org conventions, used by password managers).
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                          "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private func poll() {
        let kept = Self.pruned(items, now: Date(), keep: Self.keepSeconds)
        if kept.count != items.count { items = kept }
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard pb.changeCount != ownChange else { return }   // our own copy-back
        if #available(macOS 15.4, *) {
            denied = pb.accessBehavior == .alwaysDeny
            if denied { return }
        }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes), let text = pb.string(forType: .string) else { return }
        add(text)
    }

    /// Newest first; a repeat moves to the top; pinned items stay; at most `maxItems`.
    func add(_ raw: String, now: Date = Date()) {
        items = Self.adding(raw, to: items, now: now)
    }

    static func adding(_ raw: String, to items: [Item], now: Date) -> [Item] {
        guard !raw.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, raw.count <= maxLength else { return items }
        let old = items.first { $0.text == raw }
        var out = items.filter { $0.text != raw }
        out.insert(Item(text: raw, copied: now, pinned: old?.pinned ?? false), at: 0)
        // Over the limit: drop the oldest unpinned ones.
        while out.count > maxItems, let i = out.lastIndex(where: { !$0.pinned }) { out.remove(at: i) }
        return out
    }

    /// Drops unpinned items older than `keep`, so the history does not sit in memory for good.
    static func pruned(_ items: [Item], now: Date, keep: TimeInterval) -> [Item] {
        items.filter { $0.pinned || now.timeIntervalSince($0.copied) < keep }
    }

    /// Roughly what the history holds in memory (the text, as UTF-8).
    var bytes: Int { items.reduce(0) { $0 + $1.text.utf8.count } }

    /// Puts an item back on the clipboard (without recording it again).
    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        ownChange = pb.changeCount
        add(item.text)
        NoticeCenter.shared.post(IslandNotice(icon: "doc.on.clipboard.fill", tint: .white, title: "已複製",
                                              detail: String(item.text.replacingOccurrences(of: "\n", with: " ").prefix(40)),
                                              trailing: "✓"), seconds: 1.4)
    }

    func togglePin(_ item: Item) {
        guard let i = items.firstIndex(of: item) else { return }
        items[i].pinned.toggle()
    }

    func remove(_ item: Item) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll { !$0.pinned } }
}

/// The 暫存 page's "剪貼簿" side: recent copies, pinned ones first; click to copy back.
struct ClipboardView: View {
    @ObservedObject private var clip = ClipboardHistory.shared
    @State private var hovered: UUID?

    var body: some View {
        let list = clip.items.filter(\.pinned) + clip.items.filter { !$0.pinned }
        Group {
            if clip.denied {
                note("macOS 不允許讀取剪貼簿：到「系統設定 › 隱私權與安全性 › 從其他 App 貼上」允許 GrindIsland")
            } else if list.isEmpty {
                note("複製文字後會出現在這裡（只存在記憶體，結束 app 就清空）")
            } else {
                ScrollView(.vertical, showsIndicators: false) {
                    LazyVStack(spacing: 4) { ForEach(list) { row($0) } }
                        .padding(.horizontal, 22).padding(.vertical, 4)
                }
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    private func note(_ t: String) -> some View {
        VStack(spacing: 6) {
            Image(systemName: "doc.on.clipboard").font(.system(size: 22)).foregroundColor(.white.opacity(0.5))
            Text(t).font(.system(size: 11)).foregroundColor(.white.opacity(0.55)).multilineTextAlignment(.center)
        }
        .padding(.horizontal, 40)
    }

    private func row(_ item: ClipboardHistory.Item) -> some View {
        HStack(spacing: 8) {
            Image(systemName: item.pinned ? "pin.fill" : "text.alignleft").font(.system(size: 10))
                .foregroundColor(item.pinned ? .orange : .white.opacity(0.4)).frame(width: 14)
            Text(item.text.replacingOccurrences(of: "\n", with: " ⏎ ")).font(.system(size: 11.5)).foregroundColor(.white.opacity(0.9))
                .lineLimit(1).truncationMode(.tail)
            Spacer(minLength: 4)
            if hovered == item.id {
                iconButton(item.pinned ? "pin.slash" : "pin", item.pinned ? "取消釘選" : "釘選") { clip.togglePin(item) }
                iconButton("xmark", "移除") { withAnimation(.spring(response: 0.3, dampingFraction: 0.85)) { clip.remove(item) } }
            } else {
                Text(item.copied.formatted(date: .omitted, time: .shortened)).font(.system(size: 9.5)).monospacedDigit()
                    .foregroundColor(.white.opacity(0.35))
            }
        }
        .padding(.horizontal, 8).padding(.vertical, 5)
        .background(RoundedRectangle(cornerRadius: 7).fill(Color.white.opacity(hovered == item.id ? 0.1 : 0.05)))
        .contentShape(Rectangle())
        .onHover { hovered = $0 ? item.id : (hovered == item.id ? nil : hovered) }
        .onTapGesture { clip.copy(item) }
        .onDrag { NSItemProvider(object: item.text as NSString) }
        .help("點一下複製")
    }

    private func iconButton(_ icon: String, _ label: String, _ action: @escaping () -> Void) -> some View {
        Image(systemName: icon).font(.system(size: 10, weight: .semibold)).foregroundColor(.white.opacity(0.8))
            .frame(width: 20, height: 20).background(Circle().fill(Color.white.opacity(0.1))).contentShape(Circle())
            .onTapGesture(perform: action).help(label)
    }
}
